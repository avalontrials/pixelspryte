"""
PixelSpryte EDL Schema
Pydantic models for Edit Decision List validation.
"""

from pydantic import BaseModel, Field
from typing import List, Optional


class KeepSegment(BaseModel):
    """A segment of video to keep in the final edit."""
    idx: int
    src_file: str
    keep_start: float
    keep_end: float
    reason: Optional[str] = None
    zoom: Optional[float] = None          # e.g. 1.10 for 10% zoom
    jumpcut: Optional[bool] = False
    lower_third: Optional[str] = None     # Text overlay
    broll_query: Optional[str] = None     # Search term for B-roll insert
    caption_text: Optional[str] = None    # Styled caption text


class BrollSpec(BaseModel):
    """A B-roll insert suggested by the planner (source-time range)."""
    start: float                          # Source seconds where B-roll begins
    end: float                            # Source seconds where it ends
    query: str                            # Search term against the tag library


class MusicSpec(BaseModel):
    """Music track specification."""
    track: Optional[str] = None
    duck_to_db: float = -20.0


class Loudness(BaseModel):
    """Audio loudness targets."""
    target_lufs: float = -14.0


class EDLPlan(BaseModel):
    """
    Complete Edit Decision List generated by the LLM planner.
    Validated before passing to the Resolve driver.
    """
    title: str = "Auto Edit"
    keep_segments: List[KeepSegment]
    cut_segments: List[int] = Field(default_factory=list)
    music: MusicSpec = MusicSpec()
    loudness: Loudness = Loudness()
    captions_style: str = "none"
    hook: List[KeepSegment] = Field(default_factory=list)
    highlights: List[dict] = Field(default_factory=list)
    broll: List[BrollSpec] = Field(default_factory=list)

    def total_duration(self) -> float:
        """Calculate total kept duration in seconds."""
        return sum(
            seg.keep_end - seg.keep_start
            for seg in self.keep_segments
        )

    def summary(self) -> str:
        """Human-readable summary of the plan."""
        dur = self.total_duration()
        return (
            f"EDL: {self.title}\n"
            f"  Keep: {len(self.keep_segments)} segments ({dur/60:.1f} min)\n"
            f"  Cut:  {len(self.cut_segments)} segments\n"
            f"  Hook segments: {len(self.hook)}\n"
            f"  Captions: {self.captions_style}\n"
            f"  Music: {self.music.track or 'none'}"
        )

